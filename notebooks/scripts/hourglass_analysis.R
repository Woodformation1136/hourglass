# Bin expression by pseudotime
# ------------------------------------------------------------------------------
bin_expression <- function(
    seurat_obj,
    pseudotime_mtx, 
    branch_id, 
    lineage,
    exclude = c(),
    exclude_gene = c(),
    prefix, 
    n_bins
) {
  # get pseudotime values
  pt <- pseudotime_mtx[, lineage]
  
  # keep only cells belongs to the lineage
  keep <- branch_id %>% grepl(lineage, .)
  keep <- keep & (!seurat_obj$cell_label %in% exclude)
  pt <- pt[keep]
  
  # set bins 
  bins <- cut(
    pt, 
    breaks = seq(
      min(pt, na.rm =TRUE),
      max(pt, na.rm =TRUE),
      length.out = n_bins + 1    
    ),
    # breaks = quantile(
    #   pt, 
    #   probs = seq(0, 1, length.out = n_bins + 1)
    # ),
    labels = FALSE, 
    include.lowest = TRUE
  )
  names(bins) <- names(pt)
  
  # subset lineage cells
  obj <- subset(seurat_obj, cells = names(pt))
  obj$bin <- sprintf("%s-%02d", prefix, bins[colnames(obj)])
  
  # aggregate pseudotime
  pb <- AggregateExpression(
    obj,
    features = setdiff(rownames(obj), exclude_gene),
    assays = "RNA", 
    group.by = "bin"
  )$RNA
  pb <- pb[, order(colnames(pb)), drop = FALSE]
  
  # # report cell label composition by bins
  # comp <- table(
  #   bin = factor(obj$bin, levels = sprintf("%s-%02d", prefix, 1:n_bins)),
  #   cell_type = seurat_obj$cell_label[keep]
  # )
  # 
  # # retain only bins with number of cells > min_cells
  # bin_names <- sprintf("%s-%02d", prefix, 1:n_bins)
  # passed_bin <- bin_names[rowSums(comp) > min_cells]
  # pb <- pb[, passed_bin]
  # comp <- comp[passed_bin, ]
  # 
  # return(list(Pseudobulk = pb, Composition = comp))
  
  # report cell label composition by bins
  comp <- table(
    bin = factor(bins, levels = 1:n_bins),
    cell_type = seurat_obj$cell_label[keep]
  )
  return(list(Pseudobulk = pb, Composition = comp))
}
