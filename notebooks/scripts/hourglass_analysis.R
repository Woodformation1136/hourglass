# Run slingshot
# ------------------------------------------------------------------------------
slingshot_manual <- function(seurat_obj, lineage_cell_types) {
  lineages <- new("SlingshotDataSet")
  
  # add cell embedding
  emb <- Embeddings(seurat_obj, reduction = "pca") #[, 1:10]
  lineages@reducedDim <- as.matrix(emb)
  
  # add cluster matrix
  clusters <- seurat_obj$cell_label # factor
  mtx_clus <- matrix(0, nrow=length(clusters), ncol=length(levels(clusters)))
  row.names(mtx_clus) <- names(clusters)
  colnames(mtx_clus) <- levels(clusters)
  for (i in seq(length(clusters))) {
    mtx_clus[names(clusters)[i], clusters[i]] <- 1
  }
  lineages@clusterLabels <- mtx_clus
  
  # add lineages
  lineages@lineages <- lineage_cell_types

  
  # add adjacency matrix
  mtx_adj <- matrix(0, nrow = length(levels(clusters)), ncol = length(levels(clusters)))
  row.names(mtx_adj) <- colnames(mtx_adj) <- levels(clusters)
  for (l_i in lineages@lineages) {
    for (c_i in seq(length(l_i) - 1)) {
      mtx_adj[l_i[c_i], l_i[c_i + 1]] <- 1
      mtx_adj[l_i[c_i + 1], l_i[c_i]] <- 1
    }
  }
  lineages@adjacency <- mtx_adj
  
  # fit curves
  curves <- getCurves(
    lineages,
    approx_points = 100,
    reassign = FALSE
  ) %>% SlingshotDataSet
  
  # estimate pseudotime
  pseudotime <- slingPseudotime(
    curves,
    na = FALSE
  )
  branch_id <- slingBranchID(
    curves
  )
  return(
    list(
      SlingshotDataSet = curves,
      pseudotime = pseudotime,
      branch_id = branch_id
    )
  )
}

slingshot_manual_assign_start <- function(seurat_obj, lineage_cell_types) {
  sce_list <- list()
  pseudotime <- matrix(
    data = NA,
    nrow = length(Cells(seurat_obj)),
    ncol = length(lineage_cell_types)
  )
  branch_id <- rep(0, length(Cells(seurat_obj)))
  rownames(pseudotime) <- Cells(seurat_obj)
  names(branch_id) <- Cells(seurat_obj)
  for (L_i in seq_along(lineage_cell_types)) {
    sce_Li <- as.SingleCellExperiment(
      subset(seurat_obj, cell_label %in% lineage_cell_types[[L_i]])
    )
    len_L_i <- length(lineage_cell_types[[L_i]])
    sce_Li <- slingshot(
      sce_Li,
      clusterLabels = "cell_label",
      reducedDim = "PCA",
      start.clus = lineage_cell_types[[L_i]][1],
      end.clus = lineage_cell_types[[L_i]][len_L_i]
    )
    
    # record results
    sce_list[[L_i]] <- sce_Li
    pseudotime[Cells(sce_Li), L_i] <- sce_Li$slingPseudotime_1
    branch_id[Cells(sce_Li)] <- L_i
  }
  branch_id <- factor(branch_id, levels = seq_along(lineage_cell_types))
  
  return(
    list(
      SlingshotDataSet = sapply(sce_list, as.SlingshotDataSet),
      pseudotime = pseudotime,
      branch_id = branch_id
    )
  )
}

