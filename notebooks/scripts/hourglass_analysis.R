# import cell label
import_cell_label <- function(
  seurat_obj, 
  cell_label_file, 
  cluster_levels = NULL,
  keep_only_transfer_pass = TRUE
) {
  # Per-cell labels generated by Transfer_cell_label.Rmd.
  cell_label <- read.csv(
    cell_label_file,
    stringsAsFactors = FALSE,
    check.names = FALSE
  )

  # if keep only transfer pass
  if (keep_only_transfer_pass) {
    if (!"transfer_pass" %in% colnames(cell_label)) {
      stop(
        "keep_only_transfer_pass = TRUE, but the cell-label CSV has no ",
        "transfer_pass column."
      )
    }
    transfer_pass <- cell_label$transfer_pass %in% c(
      TRUE, 1, "1", "TRUE", "True", "true"
    )
    cell_label$cell_label[!transfer_pass] <- NA_character_
  }

  # vector cell_label
  cell_labels_by_barcode <- cell_label$cell_label[
    match(
      Cells(seurat_obj),
      cell_label$Barcode
    )
  ]
  names(cell_labels_by_barcode) <- Cells(seurat_obj)

  # import to seurat object
  seurat_obj$cell_label <- factor(
    cell_labels_by_barcode,
    levels = cluster_levels
  )
  Idents(seurat_obj) <- "cell_label"

  return(seurat_obj)
}

# Pairwise similarity
# ------------------------------------------------------------------------------
# log2CPM on a gene expression matrix (normalized each column)
logcpm <- function(x) {
  log2(1 + 1e6 * sweep(as.matrix(x), 2, colSums(x), "/"))
}

# Calculate Jensen-Shannon similarity; return a matrix similar to `cor`
calculate_js_similarity <- function(mat1, mat2) {
  out <- sccore::jsDist(cbind(mat1, mat2))[
    1:ncol(mat1),
    (ncol(mat1)+1):(ncol(mat1)+ncol(mat2))
  ]
  rownames(out) <- colnames(mat1)
  colnames(out) <- colnames(mat2)
  return(1 - out)
}

# Calculate pairwise similarity between pseudobulk profiles
# Available metrics are: `spearman`, `pearson`, and `Jensen-Shannon`
calculate_similarity <- function(mat1, mat2, metrics, norm_func = logcpm) {
  stopifnot(metrics %in% c("spearman", "pearson", "Jensen-Shannon"))
  mat1 <- as.matrix(mat1)
  mat2 <- as.matrix(mat2)
  if (metrics %in% c("spearman", "pearson")) {
    cor(
      x = norm_func(mat1),
      y = norm_func(mat2),
      method = metrics
    )
  } else if (metrics == "Jensen-Shannon") {
    calculate_js_similarity(
      as.matrix(mat1),
      as.matrix(mat2)
    )
  }
}
